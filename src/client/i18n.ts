export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem('genesis.lang');
    if (saved === 'bg' || saved === 'en' || saved === 'de') return saved;
  } catch { /* no storage */ }
  const nav = (navigator.language || 'en').slice(0, 2);
  return nav === 'bg' ? 'bg' : nav === 'de' ? 'de' : 'en';
}
